  String _t(String key) => _data[code]?[key] ?? _data['en']![key] ?? key;

  /// Used for ids stored in the database (order status, garment fields...).
  /// Falls back to the English [fallback] when no translation exists.
  String dyn(String id, String fallback) {
    final v = _data[code]?[id] ?? _data['en']?[id];
    if (v == null) return fallback;
    return v;
  }

  /// Like [dyn] but returns null when the translation is empty (used for optional hints).
  String? dynOrNull(String id, String? fallback) {
    final v = _data[code]?[id];
    if (v == null) return fallback;
    return v.isEmpty ? null : v;
  }

  String _p(String key, Map<String, Object> values) {
    var s = _t(key);
    values.forEach((k, v) => s = s.replaceAll('{$k}', '$v'));
    return s;
  }

  String _plural(String key, int n) {
    final one = _data[code]?['$key#one'];
    final two = _data[code]?['$key#two'];
    final other = _data[code]?['$key#other'] ?? _data['en']!['$key#other']!;
    final String form;
    if (n == 1 && one != null) {
      form = one;
    } else if (n == 2 && two != null) {
      form = two;
    } else {
      form = other;
    }
    return form.replaceAll('{n}', '$n');
  }

