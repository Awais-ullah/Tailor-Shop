/// Languages the app supports. `code` is also what we store in SharedPreferences.
class AppLanguage {
  const AppLanguage(this.code, this.nativeName,
      {this.rtl = false, this.flutterCode});
  final String code;
  final String nativeName;
  final bool rtl;

  /// Roman Urdu is written in English letters, so it uses the 'en' locale.
  final String? flutterCode;
  Locale get locale => Locale(flutterCode ?? code);

  static const List<AppLanguage> all = [
    AppLanguage('en', 'English'),
    AppLanguage('ur', 'Urdu', rtl: true),
    AppLanguage('ru', 'Roman Urdu', flutterCode: 'en'),
    AppLanguage('ar', 'Arabic', rtl: true),
    AppLanguage('zh', 'Chinese'),
    AppLanguage('hi', 'Hindi'),
  ];

  static AppLanguage? byCode(String? code) {
    for (final l in all) {
      if (l.code == code) return l;
    }
    return null;
  }

  static List<Locale> get supportedLocales =>
      {for (final l in all) l.locale}.toList();
}

